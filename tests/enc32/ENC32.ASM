; The 32-bit encoder's test (tests/selftest.py): every instruction line
; says, after '; =', what capstone reads from the bytes tasm.py makes and
; how many bytes that is.  Written for the kit; no game's code.

.386
CODE SEGMENT PARA PUBLIC USE32 'CODE'
ASSUME CS:CODE, DS:CODE

START:
    MOV EAX, EBX                    ; = mov eax, ebx [2]
    MOV AX, BX                      ; = mov ax, bx [3]
    MOV AL, BL                      ; = mov al, bl [2]
    MOV EAX, 12345678H              ; = mov eax, 0x12345678 [5]
    MOV AX, 1234H                   ; = mov ax, 0x1234 [4]
    MOV CL, 5                       ; = mov cl, 5 [2]
    MOV EAX, VAR                    ; = mov eax, dword ptr [VAR] [5]
    MOV VAR, EAX                    ; = mov dword ptr [VAR], eax [5]
    MOV EBX, VAR                    ; = mov ebx, dword ptr [VAR] [6]
    MOV AX, WVAR                    ; = mov ax, word ptr [WVAR] [6]
    MOV EAX, OFFSET VAR             ; = mov eax, VAR [5]
    MOV EDX, [EBX]                  ; = mov edx, dword ptr [ebx] [2]
    MOV EDX, [EBP]                  ; = mov edx, dword ptr [ebp] [3]
    MOV EDX, [ESP]                  ; = mov edx, dword ptr [esp] [3]
    MOV EDX, [ESP+8]                ; = mov edx, dword ptr [esp + 8] [4]
    MOV EDX, [EBX+ESI]              ; = mov edx, dword ptr [ebx + esi] [3]
    MOV EDX, [EBX+ESI*4+10H]        ; = mov edx, dword ptr [ebx + esi*4 + 0x10] [4]
    MOV EDX, [ESI*2+1000H]          ; = mov edx, dword ptr [esi*2 + 0x1000] [7]
    MOV EDX, [EAX+100H]             ; = mov edx, dword ptr [eax + 0x100] [6]
    MOV EDX, [EAX-4]                ; = mov edx, dword ptr [eax - 4] [3]
    MOV EDX, VAR[EBX]               ; = mov edx, dword ptr [ebx + VAR] [6]
    MOV BYTE PTR [EDI], 7           ; = mov byte ptr [edi], 7 [3]
    MOV WORD PTR [EDI], 7           ; = mov word ptr [edi], 7 [5]
    MOV DWORD PTR [EDI], 7          ; = mov dword ptr [edi], 7 [6]
    MOV AL, ES:[EDI]                ; = mov al, byte ptr es:[edi] [3]
    MOV AX, FS:[EDI]                ; = mov ax, word ptr fs:[edi] [4]
    MOV AL, ES:[DI]                 ; = mov al, byte ptr es:[di] [4]
    MOV DS, AX                      ; = mov ds, eax [2]
    MOV AX, DS                      ; = mov ax, ds [3]
    MOV EAX, DS                     ; = mov eax, ds [2]
    MOV ES, WVAR                    ; = mov es, word ptr [WVAR] [6]
    MOV WVAR, GS                    ; = mov word ptr [WVAR], gs [7]
    MOVZX EAX, BYTE PTR [ESI]       ; = movzx eax, byte ptr [esi] [3]
    MOVZX EAX, WORD PTR [ESI]       ; = movzx eax, word ptr [esi] [3]
    MOVSX AX, BL                    ; = movsx ax, bl [4]
    ADD EAX, EBX                    ; = add eax, ebx [2]
    ADD EAX, 5                      ; = add eax, 5 [5]
    ADD EBX, 5                      ; = add ebx, 5 [3]
    ADD EBX, 500H                   ; = add ebx, 0x500 [6]
    SUB EBX, -1                     ; = sub ebx, -1 [3]
    AND EBX, 0FFFFFF80H             ; = and ebx, 0xffffff80 [3]
    AND EAX, 0FEH                   ; = and eax, 0xfe [5]
    CMP BYTE PTR [EBX], 3           ; = cmp byte ptr [ebx], 3 [3]
    CMP WORD PTR VAR, 3             ; = cmp word ptr [VAR], 3 [8]
    CMP AX, 3                       ; = cmp ax, 3 [4]
    XOR ECX, [EDX+4]                ; = xor ecx, dword ptr [edx + 4] [3]
    OR [EDX+4], CX                  ; = or word ptr [edx + 4], cx [4]
    INC EAX                         ; = inc eax [1]
    DEC CX                          ; = dec cx [2]
    INC BYTE PTR [EBX]              ; = inc byte ptr [ebx] [2]
    NEG EAX                         ; = neg eax [2]
    MUL DWORD PTR [ESI]             ; = mul dword ptr [esi] [2]
    IMUL EAX, EBX                   ; = imul eax, ebx [3]
    IMUL EAX, EBX, 10               ; = imul eax, ebx, 0xa [3]
    IMUL ECX, 1000                  ; = imul ecx, ecx, 0x3e8 [6]
    TEST EAX, 1                     ; = test eax, 1 [5]
    TEST BL, 80H                    ; = test bl, 0x80 [3]
    TEST ECX, ECX                   ; = test ecx, ecx [2]
    XCHG EAX, EBX                   ; = xchg ebx, eax [1]
    XCHG AX, BX                     ; = xchg bx, ax [2]
    XCHG CL, [ESI]                  ; = xchg byte ptr [esi], cl [2]
    LEA ESI, [EBX+ECX*8+3]          ; = lea esi, [ebx + ecx*8 + 3] [4]
    LEA EDI, VAR                    ; = mov edi, VAR [5]
    LDS ESI, FVAR                   ; = lds esi, ptr [FVAR] [6]
    LFS EDI, FVAR                   ; = lfs edi, ptr [FVAR] [7]
    SHL EAX, 1                      ; = shl eax, 1 [2]
    SHR EAX, CL                     ; = shr eax, cl [2]
    SAR DX, 3                       ; = sar dx, 3 [4]
    SHLD EAX, EDX, 4                ; = shld eax, edx, 4 [4]
    SHRD EAX, EDX, CL               ; = shrd eax, edx, cl [3]
    BT EAX, 3                       ; = bt eax, 3 [4]
    BTS [EBX], ECX                  ; = bts dword ptr [ebx], ecx [3]
    BSF ECX, EAX                    ; = bsf ecx, eax [3]
    SETNE AL                        ; = setne al [3]
    SETB BYTE PTR [EBX]             ; = setb byte ptr [ebx] [3]
    PUSH EAX                        ; = push eax [1]
    PUSH AX                         ; = push ax [2]
    PUSH ES                         ; = push es [1]
    PUSH FS                         ; = push fs [2]
    POP GS                          ; = pop gs [2]
    PUSH 5                          ; = push 5 [2]
    PUSH 1000H                      ; = push 0x1000 [5]
    PUSH OFFSET VAR                 ; = push VAR [5]
    PUSH DWORD PTR [EBX]            ; = push dword ptr [ebx] [2]
    POP VAR                         ; = pop dword ptr [VAR] [6]
    PUSH EBX ECX                    ; = push ebx [1] ; push ecx [1]
    PUSHAD                          ; = pushal [1]
    POPAD                           ; = popal [1]
    PUSHFD                          ; = pushfd [1]
    PUSHF                           ; = pushf [2]
    CDQ                             ; = cdq [1]
    CWDE                            ; = cwde [1]
    CBW                             ; = cbw [2]
    MOVSD                           ; = movsd dword ptr es:[edi], dword ptr [esi] [1]
    MOVSW                           ; = movsw word ptr es:[edi], word ptr [esi] [2]
    REP STOSD                       ; = rep stosd dword ptr es:[edi], eax [2]
    REP STOSW                       ; = rep stosw word ptr es:[edi], ax [3]
    REPNE SCASB                     ; = repne scasb al, byte ptr es:[edi] [2]
    IN AL, DX                       ; = in al, dx [1]
    IN AX, DX                       ; = in ax, dx [2]
    OUT 43H, AL                     ; = out 0x43, al [2]
    OUT DX, EAX                     ; = out dx, eax [1]
    INT 21H                         ; = int 0x21 [2]
    MOV AX, CODE                    ; = mov ax, 0 [4]
BACK:
    JE BACK                         ; = je BACK [2]
    JMP BACK                        ; = jmp BACK [2]
    LOOP BACK                       ; = loop BACK [2]
    JECXZ BACK                      ; = jecxz BACK [2]
    JNE FAR_AHEAD                   ; = jne FAR_AHEAD [6]
    JMP FAR_AHEAD                   ; = jmp FAR_AHEAD [5]
    JB NEAR_AHEAD                   ; = jb NEAR_AHEAD [2]
    JMP NEAR_AHEAD                  ; = jmp NEAR_AHEAD [2]
NEAR_AHEAD:
    CALL SUB1                       ; = call SUB1 [5]
    CALL EAX                        ; = call eax [2]
    CALL DWORD PTR [EBX+4]          ; = call dword ptr [ebx + 4] [3]
    JMP DWORD PTR TABLE[EAX*4]      ; = jmp dword ptr [eax*4 + TABLE] [7]
    JMP FWORD PTR FVAR              ; = jmp ptr [FVAR] [6]
    RET                             ; = ret [1]
    RET 8                           ; = ret 8 [3]
    RETF                            ; = retf [1]
    IRETD                           ; = iretd [1]
    DB 130 DUP (0)
FAR_AHEAD:
SUB1:
    ENTER 8, 0                      ; = enter 8, 0 [4]
    LEAVE                           ; = leave [1]
    RET                             ; = ret [1]

VAR     DD 0
WVAR    DW 0
FVAR    DF 0
TABLE   DD START, SUB1, BACK

CODE ENDS
END START
