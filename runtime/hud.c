static VgaFrame *pic;
static int sx, sy;              /* picture pixels to a font pixel */
static uint8_t ink, paper;

/* the palette entry nearest to the colour */
static uint8_t nearest(uint32_t rgb)
{
    long best = -1;
    int i, found = 0;

    for (i = 0; i < 256; i++) {
        long dr = (long)(pic->palette[i] >> 16 & 0xFF) - (long)(rgb >> 16 & 0xFF);
        long dg = (long)(pic->palette[i] >> 8 & 0xFF) - (long)(rgb >> 8 & 0xFF);
        long db = (long)(pic->palette[i] & 0xFF) - (long)(rgb & 0xFF);
        long d = dr * dr + dg * dg + db * db;
        if (best < 0 || d < best) {
            best = d;
            found = i;
        }
    }
    return (uint8_t)found;
}

/* a rectangle in font pixels, from the box's corner (ox, oy) */
static int ox, oy;

static void fill(int x, int y, int w, int h, uint8_t colour)
{
    int i, j;

    for (j = oy + y * sy; j < oy + (y + h) * sy; j++)
        for (i = ox + x * sx; i < ox + (x + w) * sx; i++)
            if (i >= 0 && i < pic->width && j >= 0 && j < pic->height)
                pic->pixels[j * pic->width + i] = colour;
}

static void text(int x, int y, const char *s)
{
    int r, b;

    for (; *s; s++, x += 6) {
        const unsigned char *rows = NULL;
        if (*s >= 'A' && *s <= 'Z')
            rows = letters[*s - 'A'];
        else if (*s >= 'a' && *s <= 'z')
            rows = letters[*s - 'a'];
        else if (*s >= '0' && *s <= '9')
            rows = digits[*s - '0'];
        if (!rows)
            continue;
        for (r = 0; r < 7; r++)
            for (b = 0; b < 5; b++)
                if (rows[r] & (0x10 >> b))
                    fill(x + b, y + r, 1, 1, ink);
    }
}

void hud_draw(VgaFrame *picture)
{
    int n, w, i;

    if (shown <= 0 || !picture || picture->width <= 0 || picture->height <= 0)
        return;
    shown--;
    pic = picture;
    /* about the same size on the screen: twice in the wide or tall modes
     * (640 and more, 400 lines and more: double scan, SVGA) */
    sx = picture->width >= 640 ? 2 : 1;
    sy = picture->height >= 400 ? 2 : 1;
    ink = nearest(0xFFFFFF);
    paper = nearest(0x000000);
    n = (int)strlen(label);
    w = (n ? 6 * n - 1 : 0) + (steps ? (n ? 5 : 0) + 4 * steps - 1 : 0);
    ox = (picture->width - w * sx) / 2;
    oy = 4 * sy;
    fill(-4, 0, w + 8, 11, paper);
    text(0, 2, label);
    for (i = 0; i < steps; i++) {
        int bx = (n ? 6 * n + 4 : 0) + 4 * i;
        if (i < value)
            fill(bx, 2, 3, 7, ink);
        else
            fill(bx, 8, 3, 1, ink);
    }
}
