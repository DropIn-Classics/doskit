static const char *label;
static int value, steps, shown;

void hud_show(const char *l, int v, int s, int pictures)
{
    label = l ? l : "";
    steps = s > 0 ? s : 0;
    value = v < 0 ? 0 : v > steps ? steps : v;
    shown = pictures;
}

